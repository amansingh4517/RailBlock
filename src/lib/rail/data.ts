function datesInclusive(start: string, end: string) {
  const out: string[] = [];
  let d = start;
  while (d <= end) {
    out.push(d);
    d = addDays(d, 1);
  }
  return out;
}

function dow(iso: string) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay();
}

export function buildWindows(sundayMega = true): WindowSlot[] {
  const days = datesInclusive(WEEK_START, HORIZON_END);
  const slots: WindowSlot[] = [];
  for (const date of days) {
    const w = dow(date);
    slots.push({
      id: `w-${date}-n`,
      date,
      startMin: 40,
      endMin: 280,
      kind: "NIGHT",
      line: "BOTH",
      fromKm: 0,
      toKm: 199,
      disruptionCost: 38,
    });
    if (w === 2 || w === 4) {
      slots.push({
        id: `w-${date}-m`,
        date,
        startMin: 670,
        endMin: 790,
        kind: "MIDDAY",
        line: "BOTH",
        fromKm: 0,
        toKm: 199,
        disruptionCost: 96,
      });
    }
    if (w === 0 && sundayMega) {
      slots.push({
        id: `w-${date}-x`,
        date,
        startMin: 480,
        endMin: 840,
        kind: "MEGA",
        line: "BOTH",
        fromKm: 0,
        toKm: 199,
        disruptionCost: 110,
      });
    }
  }
  return slots;
}

