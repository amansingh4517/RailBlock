export function stationAt(km: number): Station {
  let best = STATIONS[0];
  for (const s of STATIONS) {
    if (Math.abs(s.km - km) < Math.abs(best.km - km)) best = s;
  }
  return best;
}

export function sectionFor(km: number): SectionRow {
  return SECTIONS.find((s) => km >= s.fromKm && km <= s.toKm) ?? SECTIONS[SECTIONS.length - 1];
}
